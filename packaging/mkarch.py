#!/usr/bin/env python3
"""Build an Arch Linux package (.pkg.tar.xz) without makepkg or pacman.

usage: mkarch.py <staged-root> <output.pkg.tar.xz> --name N --version V
                 [--pkgrel 1] --desc D --url U [--license MIT]
                 [--depend X ...] [--optdepend 'x: why' ...] [--install script.sh]

The package is a tar archive whose first entries are .PKGINFO and .INSTALL,
followed by the staged files. It can be built on Fedora, Debian, Void, BSD and
installed with `pacman -U`.
"""
import argparse
import io
import os
import sys
import tarfile


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("root")
    ap.add_argument("out")
    ap.add_argument("--name", required=True)
    ap.add_argument("--version", required=True)
    ap.add_argument("--pkgrel", default="1")
    ap.add_argument("--desc", required=True)
    ap.add_argument("--url", required=True)
    ap.add_argument("--license", default="MIT")
    ap.add_argument("--packager", default="Proctor-XMPP contributors")
    ap.add_argument("--depend", action="append", default=[])
    ap.add_argument("--optdepend", action="append", default=[])
    ap.add_argument("--install")
    a = ap.parse_args()
    now = int(os.environ.get("SOURCE_DATE_EPOCH", "0"))

    entries, size = [], 0
    for dirpath, dirs, files in os.walk(a.root):
        dirs.sort()
        for name in sorted(dirs + files):
            full = os.path.join(dirpath, name)
            entries.append((full, os.path.relpath(full, a.root)))
            if os.path.isfile(full) and not os.path.islink(full):
                size += os.path.getsize(full)

    info = [
        "# Generated by Proctor packaging/mkarch.py",
        "pkgname = %s" % a.name,
        "pkgbase = %s" % a.name,
        "pkgver = %s-%s" % (a.version, a.pkgrel),
        "pkgdesc = %s" % a.desc,
        "url = %s" % a.url,
        "builddate = %d" % now,
        "packager = %s" % a.packager,
        "size = %d" % size,
        "arch = any",
        "license = %s" % a.license,
    ]
    info += ["depend = %s" % item for item in a.depend]
    info += ["optdepend = %s" % item for item in a.optdepend]
    meta = ("\n".join(info) + "\n").encode()

    def norm(ti):
        ti.uid = ti.gid = 0
        ti.uname = ti.gname = "root"
        ti.mtime = now
        return ti

    def add_bytes(tf, name, data, mode=0o644):
        ti = tarfile.TarInfo(name)
        ti.size, ti.mode = len(data), mode
        tf.addfile(norm(ti), io.BytesIO(data))

    with tarfile.open(a.out, "w:xz", format=tarfile.PAX_FORMAT) as tf:
        add_bytes(tf, ".PKGINFO", meta)
        if a.install:
            with open(a.install, "rb") as fh:
                add_bytes(tf, ".INSTALL", fh.read())
        for full, rel in entries:
            tf.add(full, arcname=rel, filter=norm, recursive=False)
    print(a.out)


if __name__ == "__main__":
    sys.exit(main())
